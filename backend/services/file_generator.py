    @staticmethod
    def create_zip_archive(files: List[Tuple[str, Union[bytes, str]]]) -> bytes:
        """
        Creates an in-memory ZIP archive from a list of (filename, content_bytes_or_str).
        """
        zip_buffer = io.BytesIO()
        with zipfile.ZipFile(zip_buffer, mode="w", compression=zipfile.ZIP_DEFLATED) as zf:
            for filename, content in files:
                if isinstance(content, str):
                    data = content.encode("utf-8")
                else:
                    data = content
                zf.writestr(filename, data)

        zip_buffer.seek(0)
        return zip_buffer.getvalue()

    @staticmethod
    def custom_document_to_pdf(
        title: str,
        content: str,
        author: Optional[str] = None,
    ) -> bytes:
        """
        Generates a standalone, beautifully styled PDF document from custom text/markdown.
        """
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            rightMargin=48,
            leftMargin=48,
            topMargin=48,
            bottomMargin=48,
        )

        styles = getSampleStyleSheet()

        title_style = ParagraphStyle(
            "DocTitle",
            parent=styles["Heading1"],
            fontSize=22,
            leading=26,
            textColor=colors.HexColor("#111827"),
            spaceAfter=6,
        )

        meta_style = ParagraphStyle(
            "DocMeta",
            parent=styles["Normal"],
            fontSize=9.5,
            leading=13,
            textColor=colors.HexColor("#6B7280"),
            spaceAfter=12,
        )

        body_style = ParagraphStyle(
            "DocBody",
            parent=styles["Normal"],
            fontSize=10,
            leading=14.5,
            textColor=colors.HexColor("#1F2937"),
            spaceAfter=10,
        )

        story = []

        safe_title = (title or "Document").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        story.append(Paragraph(safe_title, title_style))

        meta_parts = [f"Generated: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}"]
        if author:
            safe_author = author.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            meta_parts.append(f"Author / Recipient: {safe_author}")
        meta_parts.append("QueryMind Knowledge Workspace")

        story.append(Paragraph(" &bull; ".join(meta_parts), meta_style))
        story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#E5E7EB"), spaceAfter=14))

        # Split content into paragraphs
        paragraphs = content.split("\n\n")
        for p in paragraphs:
            p_clean = p.strip()
            if not p_clean:
                continue
            safe_p = (
                p_clean.replace("&", "&amp;")
                .replace("<", "&lt;")
                .replace(">", "&gt;")
                .replace("\n", "<br/>")
            )
            story.append(Paragraph(safe_p, body_style))

        story.append(Spacer(1, 16))
        story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#E5E7EB"), spaceAfter=8))
        story.append(
            Paragraph(
                "<i>Document produced programmatically by QueryMind Knowledge Operating System.</i>",
                meta_style,
            )
        )

        doc.build(story)
        buffer.seek(0)
        return buffer.getvalue()

